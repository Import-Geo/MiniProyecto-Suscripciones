    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        // Verificamos que haya algo que mostrar
        if (contador == 0) {
            this.jLabel2.setText("No hay suscripciones registrdo.");
            return;
        }
        
        StringBuilder textoAMostrar = new StringBuilder();
        
        for (int i = 0; i < contador; i++) {
            textoAMostrar.append("Suscripción [").append(i + 1).append("] -> ")
                         .append(arregloSuscripciones[i].toString())
                         .append("\n"); // Salto de línea
        }
        
        this.jTextArea1.setText(textoAMostrar.toString());
        this.jLabel2.setText("Mostrar todas las suscripciones");
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        if (contador == 0) {
            this.jLabel2.setText("No hay infi para ordenar");
            return;
        }

        //por seleccion
        for (int i = 0; i < contador - 1; i++) {
            int indiceMenor = i;
            for (int j = i + 1; j < contador; j++) {
                // Comparamos los costos (si el de J es menor que el de indiceMenor)
                if (arregloSuscripciones[j].getCostoMensual() < arregloSuscripciones[indiceMenor].getCostoMensual()) {
                    indiceMenor = j;
                }
            }
            // Hacemos el intercambio (swap) de los objetos completos
            Suscripcion temporal = arregloSuscripciones[indiceMenor];
            arregloSuscripciones[indiceMenor] = arregloSuscripciones[i];
            arregloSuscripciones[i] = temporal;
        }
        // para mistrar
        StringBuilder textoAMostrar = new StringBuilder();
        for (int i = 0; i < contador; i++) {
            textoAMostrar.append("Suscripción [").append(i + 1).append("] -> ")
                         .append(arregloSuscripciones[i].toString())
                         .append("\n");
        }
        this.jTextArea1.setText(textoAMostrar.toString());
        
        this.jLabel2.setText("Ordenado por Costo de menor a mayor");
    }//GEN-LAST:event_jButton3ActionPerformed

