    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if (arregloSuscripciones == null) {
            this.jLabel2.setText("Hey primero fija el limite");
            return; 
        }
        
        if (contador < arregloSuscripciones.length) {
            String servicio = this.jTextField4.getText().trim();
            String plan = this.jTextField5.getText().trim();
            String pago = this.jTextField6.getText().trim();
            String moneda = this.jTextField7.getText().trim();
            String textoCosto = this.jTextField8.getText().trim();
            
            Double costo = Double.parseDouble(textoCosto);
            
            arregloSuscripciones[contador] = new Suscripcion
                                            (servicio, plan, pago, moneda, costo);
            contador++;
            
            this.jTextField4.setText("");
            this.jTextField5.setText("");
            this.jTextField6.setText("");
            this.jTextField7.setText("");
            this.jTextField8.setText("");
            
            this.jLabel2.setText("Suscripcion agregado, ahora llevas: "
                                + contador + " de " + arregloSuscripciones.length);
            
            
            /// mostrar pantalla
            StringBuilder textoAMostrar = new StringBuilder();
            for (int i = 0; i < contador; i++){
                textoAMostrar.append("Suscripción [").append(i + 1).append("] -> ")
                             .append(arregloSuscripciones[i].toString())
                             .append("\n");
            }
            this.jTextArea1.setText(textoAMostrar.toString());
            
        } else {
            this.jLabel2.setText("Ya ingresaste lo maximo, F, ya no se ppuede mas");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed
        // TODO add your handling code here:
        if (contador == 0) {
            this.jLabel2.setText("Esto esta vacio");
            return;
        }
        
        String palabraClave = this.jTextField3.getText().trim();
        boolean encontrado = false;
        
        // Búsqueda lineal manual
        for (int i = 0; i < contador; i++) {
            // comparar si es igual o no
            if (arregloSuscripciones[i].getServicio().equalsIgnoreCase(palabraClave)) {
                this.jTextArea1.setText("Busqueda listo \n\n" + arregloSuscripciones[i].toString());
                this.jLabel2.setText("Suscripcion encontrada en la posicion [" + (i + 1) + "]");
                encontrado = true;
                break;
            }
        }
        if (encontrado == false) {
            this.jTextArea1.setText("");
            this.jLabel2.setText("No se encontro ninguna suscripcion" + palabraClave);
        }
    }//GEN-LAST:event_jButton6ActionPerformed

